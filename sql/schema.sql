  id uuid primary key default gen_random_uuid(),
  token_hash text not null unique,
  token_hint text not null,
  account_id uuid not null references public.canva_accounts(id) on delete restrict,
  package_id uuid not null references public.canva_packages(id) on delete restrict,
  status text not null default 'active' check (status in ('active','consumed','disabled')),
  usage_limit integer not null default 1 check (usage_limit > 0),
  used_count integer not null default 0 check (used_count >= 0),
  expires_at timestamptz,
  created_by_telegram_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

