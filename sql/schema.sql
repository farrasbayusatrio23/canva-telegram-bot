do $$
begin
  if to_regclass('public.canva_access') is not null
     and not exists (
       select 1 from information_schema.columns
       where table_schema = 'public'
         and table_name = 'canva_access'
         and column_name = 'account_id'
     ) then
    if to_regclass('public.canva_access_legacy_v1') is null then
      alter table public.canva_access rename to canva_access_legacy_v1;
    end if;
  end if;
end $$;

