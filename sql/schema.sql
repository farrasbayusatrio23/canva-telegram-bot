-- Atomic token redemption. One-time tokens are usage_limit=1; reusable tokens are also supported.
create or replace function public.redeem_canva_token(
  p_token_hash text,
  p_telegram_user_id bigint,
  p_telegram_username text,
  p_telegram_first_name text,
  p_email citext
)
returns table (
  access_id uuid,
  email citext,
  account_id uuid,
  account_name text,
  package_id uuid,
  package_name text,
  duration_days integer,
  starts_at timestamptz,
  ends_at timestamptz,
  status text,
  invite_url text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_token public.canva_access_tokens%rowtype;
  v_account public.canva_accounts%rowtype;
  v_package public.canva_packages%rowtype;
  v_existing public.canva_access%rowtype;
  v_access public.canva_access%rowtype;
  v_base timestamptz;
  v_now timestamptz := now();
begin
  select * into v_token
  from public.canva_access_tokens
  where token_hash = p_token_hash
  for update;

  if not found then raise exception 'TOKEN_INVALID'; end if;
  if v_token.status = 'disabled' then raise exception 'TOKEN_DISABLED'; end if;
  if v_token.expires_at is not null and v_token.expires_at <= v_now then
    raise exception 'TOKEN_EXPIRED';
  end if;
  if v_token.used_count >= v_token.usage_limit or v_token.status = 'consumed' then
    raise exception 'TOKEN_USED';
  end if;

  select a.* into v_account from public.canva_accounts a where a.id = v_token.account_id;
  if not found or not v_account.is_active then raise exception 'ACCOUNT_DISABLED'; end if;

  select p.* into v_package from public.canva_packages p where p.id = v_token.package_id;
  if not found or not v_package.is_active then raise exception 'PACKAGE_DISABLED'; end if;

  select a.* into v_existing
  from public.canva_access a
  where a.account_id = v_account.id and a.email = p_email
  for update;

  if found
     and v_existing.telegram_user_id <> p_telegram_user_id
     and v_existing.status = 'active'
     and v_existing.ends_at > v_now then
    raise exception 'EMAIL_ALREADY_BOUND';
  end if;

  if found and v_existing.ends_at > v_now and v_existing.status = 'active' then
    v_base := v_existing.ends_at;
  else
    v_base := v_now;
  end if;

  insert into public.canva_access (
    telegram_user_id,
    telegram_username,
    telegram_first_name,
    email,
    account_id,
    package_id,
    last_token_id,
    status,
    starts_at,
    ends_at,
    removed_at,
    updated_at
  ) values (
    p_telegram_user_id,
    p_telegram_username,
    p_telegram_first_name,
    p_email,
    v_account.id,
    v_package.id,
    v_token.id,
    'active',
    case when found and v_existing.status = 'active' and v_existing.ends_at > v_now
      then v_existing.starts_at else v_now end,
    v_base + make_interval(days => v_package.duration_days),
    null,
    v_now
  )
  on conflict (account_id, email) do update set
    telegram_user_id = excluded.telegram_user_id,
    telegram_username = excluded.telegram_username,
    telegram_first_name = excluded.telegram_first_name,
    package_id = excluded.package_id,
    last_token_id = excluded.last_token_id,
    status = 'active',
    starts_at = excluded.starts_at,
    ends_at = excluded.ends_at,
    removed_at = null,
    updated_at = v_now
  returning * into v_access;

  update public.canva_access_tokens
  set used_count = used_count + 1,
      status = case when used_count + 1 >= usage_limit then 'consumed' else status end,
      updated_at = v_now
  where id = v_token.id;

  insert into public.canva_audit(account_id, access_id, email, event, details)
  values (
    v_account.id,
    v_access.id,
    p_email,
    'token_redeemed',
    jsonb_build_object(
      'token_id', v_token.id,
      'package_id', v_package.id,
      'duration_days', v_package.duration_days,
      'telegram_user_id', p_telegram_user_id
    )
  );

  return query
  select
    v_access.id,
    v_access.email,
    v_account.id,
    v_account.name,
    v_package.id,
    v_package.name,
    v_package.duration_days,
    v_access.starts_at,
    v_access.ends_at,
    v_access.status,
    v_account.invite_url;
end;
$$;

