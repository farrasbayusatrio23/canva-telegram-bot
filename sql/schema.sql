  id uuid primary key default gen_random_uuid(),
  telegram_user_id bigint not null,
  telegram_username text,
  telegram_first_name text,
  email citext not null,
  account_id uuid not null references public.canva_accounts(id) on delete restrict,
  package_id uuid not null references public.canva_packages(id) on delete restrict,
  last_token_id uuid references public.canva_access_tokens(id) on delete set null,
  status text not null default 'active' check (status in ('active','expired','removed','blocked')),
  starts_at timestamptz not null default now(),
  ends_at timestamptz not null,
  last_seen_in_canva timestamptz,
  last_checked_at timestamptz,
  removed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(account_id, email)
);

